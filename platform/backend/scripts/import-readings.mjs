// Copies the real course readings from the Course Companion (companion.html) into the backend,
// so the tutor is grounded in the same text students read. Run from platform/backend:
//   node scripts/import-readings.mjs
// Writes shared/courseReadings.js. Backend reading rd-U-N maps to companion reading U + a/b/c (e.g. rd-5-1 -> 5a).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const companion = fs.readFileSync(path.join(here, '..', '..', '..', 'companion.html'), 'utf8');
const i = companion.indexOf('const R={');
const j = companion.indexOf('\nconst GLOSS_EXTRA');
if (i < 0 || j < i) throw new Error('readings not found in companion.html');
const R = (0, eval)('(' + companion.slice(i + 8, j).trim().replace(/;$/, '') + ')');
const strip = (s) => String(s).replace(/<[^>]+>/g, '').replace(/\s+/g, ' ').trim();

const ids = ['rd-1-1', 'rd-1-2', 'rd-2-1', 'rd-2-2', 'rd-3-1', 'rd-3-2', 'rd-4-1', 'rd-5-1', 'rd-5-2', 'rd-6-1', 'rd-7-1', 'rd-7-2', 'rd-7-3', 'rd-8-1'];
const out = {};
for (const id of ids) {
  const [, u, n] = id.split('-');
  const cid = u + 'abc'[Number(n) - 1];
  const r = R[cid];
  if (!r) continue;
  const parts = [];
  if (r.def) parts.push(`${r.def.term}: ${r.def.body} Why it matters: ${r.def.why}`);
  for (const s of r.sec || []) parts.push(`${s.h}. ${strip([...(s.p || []), ...(s.list || []), ...((s.boxes || []).map((b) => b.join(': ')))].join(' '))}`);
  out[id] = { source: cid, title: `Reading ${u}.${n}: ${r.t}`, text: parts.join('\n') };
}
const file = path.join(here, '..', 'shared', 'courseReadings.js');
fs.writeFileSync(file, '// Generated by scripts/import-readings.mjs from companion.html. Do not edit by hand.\nexport const COURSE_READINGS = Object.freeze(' + JSON.stringify(out, null, 1) + ');\n');
console.log('wrote', path.relative(process.cwd(), file), Object.keys(out).length, 'readings');
